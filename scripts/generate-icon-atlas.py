#!/usr/bin/env python3
"""Builds the icon atlases from the single icon PNGs.

Every styled complication icon (the 3 "Icons style" looks: simple, hollow, full color) is one cell of a
vertical strip, so the watch needs 3 resources (2 on the black-and-white watches) instead of ~35 per style, and
the complication code can scroll the strip like a slot machine reel when an icon changes (feature_icon_atlas.c).

Sources (kept as the editable art, one PNG per icon, NOT listed in package.json any more):
    resources/common/images/<style>/<name>.png      emery + gabbro, 16x16 (sun_time_*: 20x16)
    resources/legacy/images/<style>/<name>.png      flint + diorite, 12x12 (sun_time_*: 15x12)
Outputs:
    resources/common/images/atlas_{simple,hollow,fullcolor}.png
    resources/legacy/images/atlas_{simple,hollow}.png
    src/c/generated/icon_atlas.h                    ICON_CELL_* indices, shared by all atlases

Run it (node scripts/generate-all.js does) after editing or adding an icon PNG, then rebuild.
To add an icon: put <name>.png into every style folder, append its name to CELLS below (only ever append, or
reorder on purpose: the order is the order the reel scrolls through), and use ICON_CELL_<NAME> in the C tables.
Needs Python 3 with Pillow.
"""
import os
import sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Cell order = reel order. Related icons are neighbours so a change inside a group scrolls through its relatives.
CELLS = [
    # weather conditions (the weather complication icon, day/night variants next to each other)
    'weather_sun', 'weather_moon', 'weather_partly_cloudy', 'weather_partly_cloudy_night',
    'weather_cloudy_overcast', 'weather_fog', 'weather_rain', 'weather_snow', 'weather_storm',
    # states that toggle
    'quiet_time', 'quiet_time_muted', 'bell', 'bell_off', 'bluetooth',
    'sun_time_set', 'sun_time_rise',
    # sensors and weather values
    'heart', 'foot', 'umbrella', 'droplet', 'wind', 'gps_pin', 'eye', 'cloud', 'refresh',
    # sleep
    'bed_arrow_in', 'bed_arrow_out', 'bed_check', 'bed_clock', 'bed_check_clock',
    # sky
    'planets', 'saturn_ring', 'iss', 'aurora',
]

# (source folder, cell width, cell height, styles)
TARGETS = [
    ('common', 20, 16, ['simple', 'hollow', 'fullcolor']),
    ('legacy', 15, 12, ['simple', 'hollow']),
]


def build(folder, cw, ch, style):
    atlas = Image.new('RGBA', (cw, ch * len(CELLS)), (0, 0, 0, 0))
    for i, name in enumerate(CELLS):
        path = os.path.join(ROOT, 'resources', folder, 'images', style, name + '.png')
        if not os.path.exists(path):
            sys.exit('missing icon art: ' + os.path.relpath(path, ROOT))
        im = Image.open(path).convert('RGBA')
        if im.width > cw or im.height > ch:
            sys.exit('%s is %dx%d, larger than the %dx%d cell' % (os.path.relpath(path, ROOT), im.width, im.height, cw, ch))
        if style != 'fullcolor':
            # simple / hollow are tinted at draw time and need exactly two palette entries: opaque black and clear.
            px = im.load()
            for y in range(im.height):
                for x in range(im.width):
                    px[x, y] = (0, 0, 0, 255) if px[x, y][3] >= 128 else (0, 0, 0, 0)
        atlas.paste(im, (0, i * ch))
    out = os.path.join(ROOT, 'resources', folder, 'images', 'atlas_%s.png' % style)
    atlas.save(out, optimize=True)
    return out


def write_header():
    lines = [
        '#pragma once',
        '',
        '// GENERATED by scripts/generate-icon-atlas.py -- do not edit. Index of every icon in the icon atlases',
        '// (resources/{common,legacy}/images/atlas_<style>.png): a cell is PL_SUN_ICON_DRAW_W x PL_ICON_DRAW pixels,',
        '// cell i starts at row i * PL_ICON_DRAW.',
        '',
        'enum {',
    ]
    for i, name in enumerate(CELLS):
        lines.append('  ICON_CELL_%s = %d,' % (name.upper(), i))
    lines += ['  ICON_CELL_COUNT = %d,' % len(CELLS), '};', '']
    out = os.path.join(ROOT, 'src', 'c', 'generated', 'icon_atlas.h')
    with open(out, 'w') as f:
        f.write('\n'.join(lines))
    return out


def main():
    written = []
    for folder, cw, ch, styles in TARGETS:
        for style in styles:
            written.append(build(folder, cw, ch, style))
    written.append(write_header())
    for w in written:
        print('wrote', os.path.relpath(w, ROOT))


if __name__ == '__main__':
    main()
